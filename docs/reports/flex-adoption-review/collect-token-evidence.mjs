// Review evidence only. Run with Node 24; does not change package source or dist.
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import * as tokens from "../../../packages/tokens/src/tokens.ts";
import { checkContrast, tokensCss } from "../../../packages/tokens/src/color-core.ts";
import { createTheme } from "../../../packages/tokens/src/create-theme.ts";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const directory = new URL("./", import.meta.url);
const readJson = (path) => JSON.parse(readFileSync(new URL(path, directory), "utf8"));
const inventory = readJson("inventory.json");
const baseline = inventory.baseline_commit;
// Documentation commits may advance HEAD without changing the reviewed code.
execFileSync("git", ["diff", "--quiet", baseline, "--", "packages/react", "packages/tokens"], { cwd: root });
const reactPackage = readJson("../../../packages/react/package.json");
const publicSubpaths = Object.keys(reactPackage.exports).filter((key) => key !== "." && key !== "./package.json").sort();
if (JSON.stringify(publicSubpaths) !== JSON.stringify(inventory.components.map((item) => item.subpath).sort())) {
  throw new Error("Public component inventory drifted.");
}
for (const component of inventory.components) {
  const digest = createHash("sha256").update(readFileSync(`${root}${component.entry}`)).digest("hex");
  if (digest !== component.source_sha256) throw new Error(`Entry source drifted: ${component.entry}`);
}

function semanticValues(css, mode) {
  const pattern = mode === "light" ? /:root \{([\s\S]*?)\n\}/ : /\[data-dds-theme="dark"\] \{([\s\S]*?)\n\}/;
  const block = css.match(pattern)?.[1];
  if (!block) throw new Error(`Missing ${mode} CSS block`);
  return Object.fromEntries(Object.keys(tokens.semanticColors).map((key) => {
    const value = block.match(new RegExp(`--dds-color-${key}: ([^;]+);`))?.[1];
    if (!value) throw new Error(`Missing semantic token ${key}`);
    return [key, value];
  }));
}

const contrastRows = checkContrast(tokens.palette);
const defaultCss = tokensCss(tokens.palette);
const blue = createTheme({ brand: "#2B7FFF" });
const sourceFiles = ["tokens.ts", "color-core.ts", "create-theme.ts"].map((file) => `packages/tokens/src/${file}`);
const evidence = {
  collected_on: "2026-10-08",
  baseline_commit: baseline,
  runtime: process.version,
  scope: "Source-level token output and inventory verification. No browser, visual, or full accessibility assertion.",
  versions: { react: reactPackage.version, tokens: readJson("../../../packages/tokens/package.json").version },
  inventory_verified: { public_component_subpaths: publicSubpaths.length, entry_source_hashes: inventory.components.length },
  source_hashes: Object.fromEntries(sourceFiles.map((file) => [file, createHash("sha256").update(readFileSync(`${root}${file}`)).digest("hex")])),
  counts: { palette: Object.keys(tokens.palette).length, semanticColors: Object.keys(tokens.semanticColors).length, dimension: Object.keys(tokens.dimension).length, radius: Object.keys(tokens.radius).length },
  scales: Object.fromEntries(["dimension", "radius", "fontSize", "lineHeight", "fontWeight", "shadow", "duration", "easing", "zIndex"].map((key) => [key, tokens[key]])),
  default_theme: { light: semanticValues(defaultCss, "light"), dark: semanticValues(defaultCss, "dark") },
  blue_theme: { input_brand: "#2B7FFF", hue: blue.brandHue, input_policy: "Hue only; lightness/chroma regenerated by DDS.", light: semanticValues(blue.css, "light"), dark: semanticValues(blue.css, "dark") },
  verification: { default_contrast: "passed", default_contrast_rows: contrastRows, blue_contrast: "createTheme returned successfully after its internal checks", gamut: "Both CSS outputs generated successfully through the existing gamut-checked conversion" },
};
writeFileSync(new URL("token-comparison.json", directory), `${JSON.stringify(evidence, null, 2)}\n`);
const sharedStyles = {
  "./context-menu": ["packages/react/src/dropdown-menu/dropdown-menu.css"],
  "./multi-select": ["packages/react/src/select/select.css"],
  "./data-table": ["packages/react/src/table/table.css"],
};
const componentStyles = inventory.components.map((item) => ({
  component: item.subpath.slice(2),
  files: [...new Set([...item.css_files, ...(sharedStyles[item.subpath] ?? [])])],
}));
const cssFiles = [...new Set(componentStyles.flatMap((item) => item.files))].sort();
const styleEvidence = {
  baseline_commit: baseline,
  scope: "CSS declaration excerpts, not computed styles. Includes size variants, state rules and visually hidden elements; read source selectors before interpreting. Token values are in token-comparison.json.",
  components: componentStyles,
  files: cssFiles.map((file) => {
    const source = readFileSync(`${root}${file}`, "utf8");
    const withoutComments = source.replace(/\/\*[\s\S]*?\*\//g, (comment) => comment.replace(/[^\n]/g, " "));
    return {
      file,
      source_sha256: createHash("sha256").update(source).digest("hex"),
      geometry_declarations: withoutComments.split("\n").flatMap((line, index) => {
        const declarations = [...line.matchAll(/(?<![\w-])(?:height|width|min-width|max-width|min-height|max-height|border-radius|padding(?:-[\w-]+)?|gap|font-size|line-height):\s*[^;{}]+/g)].map((match) => match[0].trim());
        return declarations.length ? [{ line: index + 1, declarations }] : [];
      }),
    };
  }),
};
writeFileSync(new URL("design-application/source-evidence.json", directory), `${JSON.stringify(styleEvidence, null, 2)}\n`);
console.log(JSON.stringify({ baseline, counts: evidence.counts, inventory: evidence.inventory_verified, css_sources: cssFiles.length, outputs: ["token-comparison.json", "design-application/source-evidence.json"] }, null, 2));
